def fill(template, **slots):
    """Подстановка слотов @@КЛЮЧ@@ (str.format не годится: в тексте есть фигурные скобки путей)."""
    for key, value in slots.items():
        assert "@@" + key + "@@" in template, key
        if key not in ("ADR_CHANGES", "N6_NOTE"):
            value = textwrap.fill(value, 112, break_long_words=False, break_on_hyphens=False)
        template = template.replace("@@" + key + "@@", value)
    assert "@@" not in template
    return template


