    d3, d5, d6 = (D3["bad"], D5["bad"], D6["bad"]) if variant == "A" else (D3["ok"], D5["ok"], D6["ok"])
    d7 = D7["undeclared"] if variant == "U" else D7["declared"]
    changes = "" if variant == "U" else ADR_CHANGES
    return fill(DESIGN_TEMPLATE, D3=d3, D5=d5, D6=d6, D7=d7, ADR_CHANGES=changes)


